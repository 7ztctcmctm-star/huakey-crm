-- 0. 为 crm_tag 添加 type 列（如不存在）
-- ============================================================
SET @col_exists = (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'huakey_crm'
    AND TABLE_NAME = 'crm_tag'
    AND COLUMN_NAME = 'type'
);
SET @sql = IF(@col_exists = 0,
    'ALTER TABLE crm_tag ADD COLUMN type VARCHAR(20) DEFAULT ''custom'' COMMENT ''标签类型: region/industry/scale/custom'' AFTER name',
    'SELECT 1'
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

